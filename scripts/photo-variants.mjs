#!/usr/bin/env node
/**
 * Generate responsive variants of every photo and write a dimensions manifest.
 *
 *   npm run photo-variants
 *   (also runs automatically at the end of `npm run optimize-photos`)
 *
 * For each source photo under public/photos this emits smaller copies next to
 * it — `foo.jpg` → `foo-w480.jpg`, `foo-w1000.jpg`, `foo-w1600.jpg` — at
 * whichever of those widths are actually smaller than the source, and writes
 * src/photoManifest.ts recording each source's intrinsic width/height and the
 * set of widths available. Components read that manifest to emit `srcset`,
 * `sizes`, and explicit `width`/`height` attributes, so a phone downloads a
 * ~40KB tile instead of the full 2000px file, and the browser can reserve the
 * image's box before it loads (no layout shift).
 *
 * Idempotent: an existing variant is left alone, and sharp is deterministic
 * for the same input, so re-running produces no git churn unless a source
 * photo actually changed. Variants are committed rather than built on the
 * host, so the repo is self-contained and a build never depends on sharp
 * being installable in the deploy environment.
 */
import { readdir, stat, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const PHOTOS_DIR = 'public/photos';
const MANIFEST_PATH = 'src/photoManifest.ts';

// Candidate widths. A variant is only produced when it's meaningfully smaller
// than the source (at least 100px narrower) — no upscaling, no near-duplicates.
// Two tiers is the sweet spot: 480 covers phone tiles, 1000 covers phone
// retina and desktop 1x. A 1600 tier was tried and dropped — it tripled the
// variant payload in the repo and only served 2x-DPR desktop tiles, which
// fall back to the full-size source anyway (exactly what happens today).
const WIDTHS = [480, 1000];
const QUALITY = 82;

/** `foo-w480.jpg` — a variant this script produced; never treated as a source. */
const VARIANT_RE = /-w\d+\.(jpe?g)$/i;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function variantPath(file, w) {
  const ext = path.extname(file);
  return file.slice(0, -ext.length) + `-w${w}` + ext;
}

async function exists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

const manifest = {};
let generated = 0;

for await (const file of walk(PHOTOS_DIR)) {
  // JPEG sources only. PNGs (the one listing screenshot) are tiny and get
  // hard-coded dimensions in their component instead.
  if (!/\.jpe?g$/i.test(file) || VARIANT_RE.test(file)) continue;

  const input = await readFile(file);
  const { width, height } = await sharp(input).metadata();
  const widths = [];

  for (const w of WIDTHS) {
    if (w > width - 100) continue;
    const out = variantPath(file, w);
    if (!(await exists(out))) {
      await sharp(input)
        .rotate()
        .resize({ width: w, withoutEnlargement: true })
        .jpeg({ quality: QUALITY, progressive: true, mozjpeg: true })
        .toFile(out);
      generated++;
      console.log(`  + ${path.relative(PHOTOS_DIR, out)}`);
    }
    widths.push(w);
  }
  widths.push(width); // the source itself is the largest candidate

  const url = '/' + path.relative('public', file).split(path.sep).join('/');
  manifest[url] = { w: width, h: height, widths };
}

const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));

const ts =
  `// GENERATED by scripts/photo-variants.mjs — do not edit by hand.\n` +
  `// Re-run \`npm run optimize-photos\` (or \`npm run photo-variants\`) after adding photos.\n\n` +
  `export interface PhotoMeta {\n  /** intrinsic width of the source file */\n  w: number;\n` +
  `  /** intrinsic height of the source file */\n  h: number;\n` +
  `  /** widths available: generated variants, ascending, ending with the source width */\n  widths: number[];\n}\n\n` +
  `export const PHOTO_MANIFEST: Record<string, PhotoMeta> = ${JSON.stringify(sorted, null, 2)};\n`;

await writeFile(MANIFEST_PATH, ts);

console.log(
  `\n${generated} variant(s) generated, ${Object.keys(sorted).length} photos in ${MANIFEST_PATH}`
);
